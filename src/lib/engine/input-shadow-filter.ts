/**
 * Input Shadow Filter
 *
 * Suppresses synthetic keyboard and mouse events injected by controller-to-desktop
 * mapping software (specifically Steam Input Desktop Configuration on Steam Deck / Linux)
 * to prevent double-firing and duplicate audio chimes when playing in Desktop Mode.
 */

import type { GamepadButtonId } from './gamepad';

/**
 * Known default Steam Input Desktop Configuration button-to-keyboard mappings.
 */
export const STEAM_DESKTOP_SHADOW_MAP: Record<GamepadButtonId, string[]> = {
  A: ['Enter', 'Return', ' '],
  B: ['Escape', 'Esc', 'b'],
  X: [' ', 'Space', 'x'],
  Y: ['Tab', 'y', 'Escape', 'i'],
  UP: ['ArrowUp', 'Up'],
  DOWN: ['ArrowDown', 'Down'],
  LEFT: ['ArrowLeft', 'Left'],
  RIGHT: ['ArrowRight', 'Right'],
  SELECT: ['Tab', 'Escape', 'Backspace'],
  START: ['Escape', 'Enter', 'Return'],
  LB: ['PageUp', 'Tab'],
  RB: ['PageDown'],
  LT: [],
  RT: [],
  L3: [],
  R3: [],
  GUIDE: [],
};

const ALL_SHADOW_KEYS = new Set([
  'enter',
  'return',
  'escape',
  'esc',
  ' ',
  'space',
  'tab',
  'arrowup',
  'up',
  'arrowdown',
  'down',
  'arrowleft',
  'left',
  'arrowright',
  'right',
  'pageup',
  'pagedown',
  'backspace',
  'a',
  'b',
  'x',
  'y',
]);

export interface ProcessKeyOptions {
  hasGamepad: boolean;
  onDispatch: () => void;
  currentlyPressedGamepadButtons?: Iterable<GamepadButtonId>;
  now?: number;
}

export class InputShadowFilter {
  private recentPresses = new Map<GamepadButtonId, number>();
  private activeGamepadButtons = new Set<GamepadButtonId>();
  private windowMs: number;
  private pendingDelayMs: number;
  private pendingTimer: ReturnType<typeof setTimeout> | null = null;
  private pendingKey: string | null = null;

  constructor(options: { windowMs?: number; pendingDelayMs?: number } = {}) {
    this.windowMs = options.windowMs ?? 350;
    this.pendingDelayMs = options.pendingDelayMs ?? 55;
  }

  /**
   * Records a physical gamepad button press down.
   * Cancels any pending synthetic shadow key waiting in the buffer.
   */
  public recordButtonDown(buttonId: GamepadButtonId, now: number = performance.now()): void {
    this.cancelPendingShadowKeys();
    this.activeGamepadButtons.add(buttonId);
    this.recentPresses.set(buttonId, now);
  }

  /**
   * Records a physical gamepad button release.
   */
  public recordButtonUp(buttonId: GamepadButtonId): void {
    this.activeGamepadButtons.delete(buttonId);
  }

  /**
   * Cancels and drops any buffered pending shadow keys.
   */
  public cancelPendingShadowKeys(): void {
    if (this.pendingTimer !== null) {
      clearTimeout(this.pendingTimer);
      this.pendingTimer = null;
      this.pendingKey = null;
    }
  }

  /**
   * Returns currently pending synthetic shadow key, if any.
   */
  public getPendingKey(): string | null {
    return this.pendingKey;
  }

  /**
   * Resets all tracked buttons, timestamps and pending timers.
   */
  public clear(): void {
    this.cancelPendingShadowKeys();
    this.recentPresses.clear();
    this.activeGamepadButtons.clear();
  }

  /**
   * Checks whether a given key is in the universe of potential Steam shadow mappings.
   */
  public isKnownShadowKey(eventKey: string): boolean {
    return ALL_SHADOW_KEYS.has(eventKey.toLowerCase());
  }

  /**
   * Determines whether an incoming OS keyboard event is an active synthetic shadow
   * generated by Steam Desktop controller mapping.
   */
  public isSyntheticKeyboardShadow(
    eventKey: string,
    currentlyPressedGamepadButtons?: Iterable<GamepadButtonId>,
    now: number = performance.now()
  ): boolean {
    if (currentlyPressedGamepadButtons) {
      for (const btn of currentlyPressedGamepadButtons) {
        this.activeGamepadButtons.add(btn);
        if (!this.recentPresses.has(btn)) {
          this.recentPresses.set(btn, now);
        }
      }
    }

    if (this.recentPresses.size === 0 && this.activeGamepadButtons.size === 0) {
      return false;
    }

    const normKey = eventKey.toLowerCase();

    for (const [btnId, timestamp] of this.recentPresses.entries()) {
      const isCurrentlyHeld = this.activeGamepadButtons.has(btnId);
      const isRecent = now - timestamp <= this.windowMs;

      if (!isCurrentlyHeld && !isRecent) {
        this.recentPresses.delete(btnId);
        continue;
      }

      // 1. Literal button name match (e.g. Button 'A' -> Key 'a')
      if (btnId.toLowerCase() === normKey) {
        return true;
      }

      // 2. Known Steam Desktop Configuration shadow mappings
      const shadows = STEAM_DESKTOP_SHADOW_MAP[btnId];
      if (shadows) {
        for (const shadow of shadows) {
          if (shadow.toLowerCase() === normKey) {
            return true;
          }
        }
      }
    }

    return false;
  }

  /**
   * High-level entry point for keyboard events:
   * 1. Drops immediately if matching a recently pressed / held controller button.
   * 2. If a Gamepad is active and the key is a known shadow mapping, buffers for 55ms.
   *    If the controller button lands within 55ms, this synthetic key is dropped cleanly.
   * 3. Otherwise dispatches immediately.
   *
   * Returns true if the key was dropped or buffered, false if caller should dispatch immediately.
   */
  public filterOrBufferKey(eventKey: string, options: ProcessKeyOptions): boolean {
    const now = options.now ?? performance.now();

    // 1. Immediate shadow drop if button was already pressed
    if (this.isSyntheticKeyboardShadow(eventKey, options.currentlyPressedGamepadButtons, now)) {
      return true;
    }

    // 2. If a Gamepad is active and key is a potential shadow, buffer briefly
    if (options.hasGamepad && this.isKnownShadowKey(eventKey)) {
      this.cancelPendingShadowKeys();
      this.pendingKey = eventKey;
      this.pendingTimer = setTimeout(() => {
        this.pendingTimer = null;
        this.pendingKey = null;
        options.onDispatch();
      }, this.pendingDelayMs);
      return true;
    }

    // 3. Normal key or no gamepad connected - proceed immediately
    return false;
  }
}
